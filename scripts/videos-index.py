"""Indexes the video ZIMs (YouTube channels packaged by Kiwix) for the Command Center's Watch pages.

Writes web/data/videos.js (collections + every video's title, length, date) and copies each video's
thumbnail to web/vthumbs/. Videos play in the Kiwix library; this only lists them.
Usage: python videos-index.py <NOMAD dir>
"""
import json, os, re, sys
from pathlib import Path
from libzim.reader import Archive

nomad = Path(sys.argv[1])
zims = sorted((nomad / "zim").glob("*.zim"))
out_thumbs = nomad / "web" / "vthumbs"
out_thumbs.mkdir(parents=True, exist_ok=True)


def seconds(iso):  # PT1H2M3S
    m = re.fullmatch(r"PT(?:(\d+)H)?(?:(\d+)M)?(?:(\d+)S)?", iso or "")
    return sum(int(x or 0) * f for x, f in zip(m.groups(), (3600, 60, 1))) if m else 0


collections, videos = [], []
for z in zims:
    a = Archive(str(z))
    try:
        channel = json.loads(bytes(a.get_entry_by_path("channel.json").get_item().content))
    except KeyError:
        continue  # not a video ZIM
    book = z.stem
    meta = lambda k: bytes(a.get_metadata(k)).decode() if k in a.metadata_keys else ""
    ci = len(collections)
    count = 0
    for i in range(a.all_entry_count):
        e = a.get_entry_by_id(i)
        if not (e.path.startswith("videos/") and e.path.endswith(".json")):
            continue
        v = json.loads(bytes(e.get_item().content))
        slug = e.path[len("videos/"):-len(".json")]
        thumb = ""
        if v.get("thumbnailPath"):
            t = out_thumbs / f"{v['id']}.webp"
            if not t.exists():
                try:
                    t.write_bytes(bytes(a.get_entry_by_path(v["thumbnailPath"]).get_item().content))
                except KeyError:
                    pass
            if t.exists():
                thumb = f"vthumbs/{t.name}"
        videos.append({"c": ci, "s": slug, "t": v.get("title", slug), "d": seconds(v.get("duration")),
                       "y": (v.get("publicationDate") or "")[:4], "th": thumb})
        count += 1
    collections.append({"book": book, "name": meta("Name"), "title": meta("Title") or channel.get("channelName", book),
                        "desc": meta("Description") or channel.get("description", ""), "count": count,
                        "channel": channel.get("channelName", "")})
    print(f"  {book}: {count} videos")

js = nomad / "web" / "data" / "videos.js"
js.write_text("// Generated by scripts/videos-index.sh. Do not edit.\n"
              f"window.VIDEO_COLLECTIONS = {json.dumps(collections)};\n"
              f"window.VIDEOS = {json.dumps(videos, separators=(',', ':'))};\n")
print(f"  {len(videos)} videos in {len(collections)} collections, {js.stat().st_size // 1024} KB index")
