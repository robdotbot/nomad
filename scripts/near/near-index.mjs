// Builds web/data/near.js: hospitals, fire stations, police, pharmacies, water, groceries and fuel
// around each home city, read from the offline map files. The map's own tiles only carry these
// places at zoom 15, so the Near Home list needs this index to show a whole city at once.
// Usage: node near-index.mjs <NOMAD dir>
import fs from 'node:fs';
import { PMTiles } from 'pmtiles';
import { VectorTile } from '@mapbox/vector-tile';
import Pbf from 'pbf';

const NOMAD = process.argv[2];
const AREAS = [   // [name, map file, west, south, east, north]
  ['Las Vegas & Henderson', 'us-west', -115.45, 35.90, -114.85, 36.35],
  ['San Antonio', 'san-antonio', -98.80, 29.20, -98.20, 29.75],
];
const KINDS = new Set(['hospital', 'clinic', 'doctors', 'fire_station', 'police', 'pharmacy', 'drinking_water', 'supermarket', 'fuel']);
const Z = 15;

class FileSource {
  constructor(path) { this.fd = fs.openSync(path, 'r'); this.path = path; }
  getKey() { return this.path; }
  async getBytes(offset, length) {
    const buf = Buffer.alloc(length); fs.readSync(this.fd, buf, 0, length, offset);
    return { data: buf.buffer.slice(buf.byteOffset, buf.byteOffset + length) };
  }
}
const lon2x = lon => Math.floor((lon + 180) / 360 * 2 ** Z);
const lat2y = lat => { const r = lat * Math.PI / 180; return Math.floor((1 - Math.log(Math.tan(r) + 1 / Math.cos(r)) / Math.PI) / 2 * 2 ** Z); };

const out = [], seen = new Set();
for (const [area, file, w, s, e, n] of AREAS) {
  const pm = new PMTiles(new FileSource(`${NOMAD}/maps/${file}.pmtiles`));
  let tiles = 0, found = 0;
  for (let x = lon2x(w); x <= lon2x(e); x++) for (let y = lat2y(n); y <= lat2y(s); y++) {
    const t = await pm.getZxy(Z, x, y); if (!t) continue; tiles++;
    const layer = new VectorTile(new Pbf(new Uint8Array(t.data))).layers.pois; if (!layer) continue;
    for (let i = 0; i < layer.length; i++) {
      const f = layer.feature(i), p = f.properties;
      if (!KINDS.has(p.kind) || f.type !== 1) continue;
      const [lon, lat] = f.toGeoJSON(x, y, Z).geometry.coordinates;
      const name = String(p['name:en'] || p.name || '');
      const key = p.kind + name + lon.toFixed(4) + lat.toFixed(4);
      if (seen.has(key)) continue; seen.add(key);
      out.push([p.kind, name, +lon.toFixed(5), +lat.toFixed(5)]); found++;
    }
  }
  console.log(`  ${area}: ${found} places from ${tiles} tiles`);
}
fs.writeFileSync(`${NOMAD}/web/data/near.js`,
  '// Generated by scripts/near-index.sh from the offline maps. [kind, name, lon, lat]\nwindow.NEAR = ' + JSON.stringify(out) + ';\n');
