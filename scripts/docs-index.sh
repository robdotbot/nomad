#!/bin/bash
# Indexes guides/ for the launcher: title, page count, size and a first-page thumbnail per file.
# Writes web/data/docs.js and web/thumbs/. Run after adding or removing guides (build.sh runs it).
source "$(dirname "$0")/lib.sh"
say "docs index"
G="$NOMAD/guides"; W="$NOMAD/web"
mkdir -p "$W/data" "$W/thumbs"
out="$W/data/docs.js"
{
  echo "// Generated by scripts/docs-index.sh. Do not edit."
  echo "window.DOCS = ["
  find "$G" -type f \( -name '*.pdf' -o -name '*.html' \) ! -path '*/bible/*' ! -name index.html | sort | while read -r f; do
    rel="${f#$G/}"; key=$(echo "$rel" | tr '/ ' '__'); thumb=""
    pages=""; [[ "$f" == *.pdf ]] && pages=$(mdls -raw -name kMDItemNumberOfPages "$f" 2>/dev/null | grep -E '^[0-9]+$' || true)
    if [[ "$f" == *.pdf ]]; then
      if [[ ! -s "$W/thumbs/$key.png" ]]; then
        t=$(mktemp -d); qlmanage -t -s 480 -o "$t" "$f" >/dev/null 2>&1 || true
        [[ -s "$t/$(basename "$f").png" ]] && mv "$t/$(basename "$f").png" "$W/thumbs/$key.png"; rm -rf "$t"
      fi
      [[ -s "$W/thumbs/$key.png" ]] && thumb="thumbs/$key.png"
    fi
    bytes=$(stat -f %z "$f")
    printf '  {path:"guides/%s", pages:%s, bytes:%s, thumb:"%s"},\n' "$rel" "${pages:-0}" "$bytes" "$thumb"
  done
  echo "];"
} > "$out"
echo "  $(grep -c path: "$out") docs, $(ls "$W/thumbs" | wc -l | tr -d ' ') thumbnails"
